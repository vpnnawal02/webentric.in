export function getProject(slug) {
  return PORTFOLIO_PROJECTS.find((p) => p.slug === slug);
}

export function getAdjacentProjects(slug) {
  const idx = PORTFOLIO_PROJECTS.findIndex((p) => p.slug === slug);
  if (idx === -1) return { prev: null, next: null };
  return {
    prev: PORTFOLIO_PROJECTS[(idx - 1 + PORTFOLIO_PROJECTS.length) % PORTFOLIO_PROJECTS.length],
    next: PORTFOLIO_PROJECTS[(idx + 1) % PORTFOLIO_PROJECTS.length],
  };
}
